$BaseDir = Split-Path -Parent $MyInvocation.MyCommand.Path

foreach ($Key in $Screens.Keys) {
    $Info = $Screens[$Key]
    $Folder = Join-Path $BaseDir $Key
    if (-not (Test-Path $Folder)) {
        New-Item -ItemType Directory -Path $Folder | Out-Null
    }
    
    $ScreenshotPath = Join-Path $Folder "screenshot.png"
    Write-Host "Downloading screenshot for $($Info.Title)..."
    Invoke-WebRequest -Uri $Info.Screenshot -OutFile $ScreenshotPath -Headers @{"User-Agent"="Mozilla/5.0"}
    
    $CodePath = Join-Path $Folder "index.$($Info.Ext)"
    Write-Host "Downloading code for $($Info.Title)..."
    Invoke-WebRequest -Uri $Info.Code -OutFile $CodePath -Headers @{"User-Agent"="Mozilla/5.0"}
}

